/** A workbook block payload (matches BlockDto minus the server-assigned id). */
export interface SeedBlock {
 type:
 | 'text'| 'image'| 'input_text'| 'input_select'| 'input_rating'| 'action_button'| 'input_file'| 'test';
 content?: string | null;
 imageUrl?: string | null;
 options?: unknown;
 blockRole?: string | null;
}

// ── tiny builders keep the content below readable ─────────────────────────
const t = (content: string, blockRole?: string): SeedBlock => ({
 type: 'text',
 content,
 blockRole: blockRole ?? null,
});
/** Slide image by 1-based deck page number → /workbook/slide-NN.png */
const img = (page: number, alt: string): SeedBlock => ({
 type: 'image',
 imageUrl: `/workbook/slide-${String(page).padStart(2, '0')}.png`,
 content: alt,
 blockRole: 'slide',
});
/** MOK workshop slide → /workbook/mok-NN.png (AIRL purple chrome). */
const mok = (page: number, alt: string): SeedBlock => ({
 type: 'image',
 imageUrl: `/workbook/mok-${String(page).padStart(2, '0')}.png`,
 content: alt,
 blockRole: 'slide',
});
const ask = (content: string): SeedBlock => ({
 type: 'input_text',
 content,
 blockRole: 'exercise',
});
const fileAsk = (content: string): SeedBlock => ({
 type: 'input_file',
 content,
 blockRole: 'task',
});
const rate = (content: string): SeedBlock => ({
 type: 'input_rating',
 content,
 options: { min: 1, max: 5 },
 blockRole: 'reflection',
});
const pick = (content: string, choices: string[]): SeedBlock => ({
 type: 'input_select',
 content,
 options: { choices },
 blockRole: 'exercise',
});
const quiz = (
 question: string,
 choices: string[],
 correctIndex: number,
): SeedBlock => ({
 type: 'test',
 options: { question, choices, correctIndex },
 blockRole: 'exercise',
});
const btn = (label: string, href: string): SeedBlock => ({
 type: 'action_button',
 options: { label, href },
 blockRole: 'task',
});
const video = (label: string, href: string): SeedBlock => ({
 type: 'action_button',
 options: { label, href, embed: true },
 blockRole: 'slide',
});
const brk = (content: string): SeedBlock => ({
 type: 'text',
 content,
 blockRole: 'break',
});

