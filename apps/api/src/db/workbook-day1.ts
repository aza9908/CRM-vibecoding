/**
 * DAY 1 — "Вайб-кодинг с Claude" workbook content.
 *
 * A single ordered array of workbook blocks, built entirely from the existing
 * block tool (text / image / input_text / input_select / test / input_rating /
 * action_button / input_file). Content is lifted from the Day-1 deck; slide
 * images are served as static assets from `apps/web/public/workbook/`.
 *
 * Structure the workshop asked for:
 *   • Point 0  — readiness checklist as tick-boxes + goal-setting mini-task
 *   • Block 1  — Теория: что такое ИИ            (~30 min) → перерыв 10 мин
 *   • Block 2  — Промпт-инжиниринг (3 упражнения) (~45 min) → перерыв 15 мин
 *   • Block 3  — Прототип в Artifacts + первый UI (~60 min): design → PRD → tech → MVP
 *   • Block 4  — Claude Code в VS Code            (~45 min)
 *   • Block 5  — ИИ-агенты, MCP и роботы          (~25 min)
 * Active budget ≈ 3 ч 40 мин + 25 мин перерывов ≈ 4 часа.
 *
 * The `blockRole` tag lets the teacher UI style structural blocks (agenda /
 * break / exercise / task / reflection) without changing the schema.
 */

/** A workbook block payload (matches BlockDto minus the server-assigned id). */
export interface SeedBlock {
  type:
    | 'text'
    | 'image'
    | 'input_text'
    | 'input_select'
    | 'input_rating'
    | 'action_button'
    | 'input_file'
    | 'test';
  content?: string | null;
  imageUrl?: string | null;
  options?: unknown;
  blockRole?: string | null;
}

// ── tiny builders keep the content below readable ─────────────────────────
const t = (content: string, blockRole?: string): SeedBlock => ({
  type: 'text',
  content,
  blockRole: blockRole ?? null,
});
/** Slide image by 1-based deck page number → /workbook/slide-NN.png */
const img = (page: number, alt: string): SeedBlock => ({
  type: 'image',
  imageUrl: `/workbook/slide-${String(page).padStart(2, '0')}.png`,
  content: alt,
  blockRole: 'slide',
});
const ask = (content: string): SeedBlock => ({
  type: 'input_text',
  content,
  blockRole: 'exercise',
});
const fileAsk = (content: string): SeedBlock => ({
  type: 'input_file',
  content,
  blockRole: 'task',
});
const rate = (content: string): SeedBlock => ({
  type: 'input_rating',
  content,
  options: { min: 1, max: 5 },
  blockRole: 'reflection',
});
const pick = (content: string, choices: string[]): SeedBlock => ({
  type: 'input_select',
  content,
  options: { choices },
  blockRole: 'exercise',
});
const quiz = (
  question: string,
  choices: string[],
  correctIndex: number,
): SeedBlock => ({
  type: 'test',
  options: { question, choices, correctIndex },
  blockRole: 'exercise',
});
const btn = (label: string, href: string): SeedBlock => ({
  type: 'action_button',
  options: { label, href },
  blockRole: 'task',
});
const brk = (content: string): SeedBlock => ({
  type: 'text',
  content,
  blockRole: 'break',
});

